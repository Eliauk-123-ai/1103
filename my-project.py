def plan_trip():
    """
    一个智能旅行计划生成器
    """
    # 预定义的旅行数据 (目的地 -> {天数 -> 行程和美食})
    travel_data = {
        "北京": {
            1: (["天安门广场", "故宫", "王府井"], "北京烤鸭, 炸酱面"),
            2: (["故宫", "天安门广场", "前门大街", "王府井"], "北京烤鸭, 炸酱面"),
            3: (["颐和园 → 故宫", "八达岭长城 → 南锣鼓巷", "天坛 → 什刹海"], "北京烤鸭, 炸酱面"),
            4: (["颐和园", "圆明园", "北京大学", "清华大学"], "北京烤鸭, 豆汁儿, 炒肝"),
            5: (["八达岭长城", "明十三陵", "鸟巢", "水立方", "奥林匹克公园"], "涮羊肉, 驴打滚"),
            6: (["天坛公园", "前门大街", "大栅栏", "杨梅竹斜街", "琉璃厂"], "卤煮, 爆肚"),
            7: (["北海公园", "景山公园", "南锣鼓巷", "后海", "五道营胡同", "雍和宫", "孔庙"], "糖葫芦, 豌豆黄")
        },
        "上海": {
            1: (["外滩", "东方明珠", "南京路步行街"], "生煎包, 小笼包"),
            2: (["上海迪士尼乐园"], "火鸡腿, 米奇冰淇淋"),
            3: (["上海博物馆", "人民广场", "新天地", "田子坊"], "白斩鸡, 蟹壳黄"),
            4: (["豫园", "城隍庙", "上海老街"], "南翔小笼, 梨膏糖"),
            5: (["复旦大学", "同济大学", "多伦路文化街"], "鲜肉月饼"),
            6: (["朱家角古镇"], "扎肉, 粽子"),
            7: (["上海科技馆", "世纪公园", "陆家嘴金融区"], "本帮酱鸭")
        },
        # 您可以按照相同格式添加更多城市，例如 西安、成都、杭州 等
    }

    print("请输入目的地 (如:北京/上海/西安/成都/杭州):", end="")
    destination = input().strip()

    if destination not in travel_data:
        print(f"抱歉，我们暂时不支持 {destination} 的旅行计划。")
        return

    try:
        days_input = input("请输入旅行天数(1-7):")
        days = int(days_input.strip())
        if days < 1 or days > 7:
            print("请输入1到7之间的天数。")
            return
    except ValueError:
        print("请输入有效的数字天数。")
        return

    itinerary, food = travel_data[destination][days]

    print(f"\n为您生成的[{destination}]{days}日游行程:")
    print("-" * 50)
    for i, day_plan in enumerate(itinerary):
        print(f"第 {i+1} 天:{day_plan}")
    print("-" * 50)
    print(f"美食推荐: {food}")
    print("祝您旅途愉快！")

# 执行旅行计划函数
if __name__ == "__main__":
    plan_trip()